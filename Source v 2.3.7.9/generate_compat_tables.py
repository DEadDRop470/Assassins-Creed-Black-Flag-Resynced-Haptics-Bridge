#!/usr/bin/env python3
"""Regenerate address-independent engine signatures and the verified 1.08 profile."""
import json
from pathlib import Path
root=Path(__file__).resolve().parent
m=json.loads((root/'References/engine_compat_patterns.json').read_text())
lines=['#pragma once','// Generated by generate_compat_tables.py. Do not edit by hand.',
       'struct CompatStateLocation {u64 slot;u64 function;};',
       'struct CompatCodePattern {u16 length;const u8* bytes;const u8* mask;};',
       'struct CompatStateModel {const char* name;i32 enter_index,exit_index;u16 bank[2][9];};']
for i,p in enumerate(m['patterns']):
    for key in ['bytes','mask']:
        values=','.join('0x'+p[key][k:k+2] for k in range(0,len(p[key]),2))
        lines.append(f'static const u8 kCompatPattern{i}_{key}[]={{'+values+'};')
lines.append('static const CompatCodePattern kCompatCodePatterns[]={')
for i,p in enumerate(m['patterns']):lines.append(f'    {{{p["length"]},kCompatPattern{i}_bytes,kCompatPattern{i}_mask}},')
lines.append('};\nstatic const CompatStateModel kCompatStateModels[]={')
for model in m['models']:
    enter=next((h['index'] for h in model['hooks'] if h['offset']==7),-1)
    exit=next((h['index'] for h in model['hooks'] if h['offset']==8),-1)
    banks=','.join('{'+','.join(map(str,b['patterns']))+'}' for b in model['banks'])
    lines.append(f'    {{"{model["name"]}",{enter},{exit},{{'+banks+'}},')
lines.append('};')
for method in ['3','4','6']:
    lines.append('static const u16 kCompatFilter'+method+'[]={'+','.join(map(str,m['common_filters'][method]))+'};')
for name,ids in m['audio_patterns'].items():
    lines.append('static const u16 kCompatAudio_'+name+'[]={'+','.join(map(str,ids))+'};')
known=m['known108']
for key in ['timestamp','image_size','flush_rva','post_event_rva','xinput_iat_rva']:
    lines.append(f'static constexpr u64 kCompat108_{key}=0x{known[key]:x}ull;')
lines.append('static const CompatStateLocation kCompat108States[]={')
for state in known['states']:lines.append(f'    {{0x{state["slot"]:x}ull,0x{state["function"]:x}ull}},')
lines.append('};')
(root/'src/compat_tables.h').write_text('\n'.join(lines)+'\n')
print(f'Generated {len(m["models"])} state models, {len(m["patterns"])} code patterns and 21 verified 1.08 locations')
